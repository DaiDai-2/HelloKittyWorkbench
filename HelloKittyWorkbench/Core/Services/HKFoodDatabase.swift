    /// 查询食物热量
    static func searchFood(_ query: String) -> (name: String, caloriesPer100g: Double, typicalPortion: String, typicalCalories: Double)? {
        let lowerQuery = query.lowercased()
        
        for food in foods {
            for keyword in food.keywords {
                if lowerQuery.contains(keyword.lowercased()) {
                    return calculateTypicalPortion(food)
                }
            }
        }
        
        // 模糊匹配
        for food in foods {
            if food.name.lowercased().contains(lowerQuery) || lowerQuery.contains(food.name.lowercased()) {
                return calculateTypicalPortion(food)
            }
        }
        
        return nil
    }
    
    /// 计算一份典型份量的热量
    private static func calculateTypicalPortion(_ food: (name: String, caloriesPer100g: Double, keywords: [String])) -> (name: String, caloriesPer100g: Double, typicalPortion: String, typicalCalories: Double) {
        var portion = "100g"
        var typicalGrams: Double = 100
        
        switch food.name {
        case "米饭": portion = "1碗(150g)"; typicalGrams = 150
        case "面条": portion = "1碗(200g)"; typicalGrams = 200
        case "馒头": portion = "1个(80g)"; typicalGrams = 80
        case "包子": portion = "1个(60g)"; typicalGrams = 60
        case "饺子": portion = "10个(200g)"; typicalGrams = 200
        case "鸡蛋": portion = "1个(50g)"; typicalGrams = 50
        case "苹果": portion = "1个(200g)"; typicalGrams = 200
        case "香蕉": portion = "1根(120g)"; typicalGrams = 120
        case "牛奶": portion = "1杯(250ml)"; typicalGrams = 250
        case "酸奶": portion = "1杯(200g)"; typicalGrams = 200
        case "全麦面包": portion = "2片(60g)"; typicalGrams = 60
        case "猪肉（瘦肉）": portion = "1份(150g)"; typicalGrams = 150
        case "牛肉": portion = "1份(150g)"; typicalGrams = 150
        case "鸡肉": portion = "1份(150g)"; typicalGrams = 150
        case "奶茶": portion = "1杯(500ml)"; typicalGrams = 500
        case "薯片": portion = "1包(75g)"; typicalGrams = 75
        default: break
        }
        
        let calories = food.caloriesPer100g * typicalGrams / 100
        return (food.name, food.caloriesPer100g, portion, calories)
    }
